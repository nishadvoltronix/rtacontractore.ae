import {copyFile,mkdir,readFile,writeFile,access} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {PRESETS,PRESET_LABELS,availableDays} from './lib/model.mjs';
const args=process.argv.slice(2);
if(args.length!==2||args[0]!=='--project-dir')throw new Error('Usage: node install-content.mjs --project-dir EXISTING_CANONICAL_DATA_APP');
const target=resolve(args[1]),here=fileURLToPath(new URL('./',import.meta.url));
await access(join(target,'AGENTS.md'));
const path=join(target,'src','data.json'),snapshot=JSON.parse(await readFile(path,'utf8'));
if(snapshot.surface!=='dashboard'||!snapshot.id||!snapshot.queries?.source_readiness||!snapshot.queries?.metric_availability)throw new Error('A reviewed RTA canonical dashboard is required');
await mkdir(join(target,'src','content','dashboard'),{recursive:true});
await mkdir(join(target,'src','content','shared'),{recursive:true});
await copyFile(join(here,'content','DashboardContent.jsx'),join(target,'src','content','dashboard','DashboardContent.jsx'));
await copyFile(join(here,'content','dashboard.css'),join(target,'src','content','dashboard','dashboard.css'));
await copyFile(join(here,'lib','model.mjs'),join(target,'src','content','shared','rta-model.js'));
const controlsSource={provider:'User-requested reporting controls',classification:'interaction contract',description:'The requested calendar presets are controls, not performance observations. Covered custom days derive solely from imported source coverage.'};
snapshot.queries.reporting_presets={rows:PRESETS.map(period=>({period,label:PRESET_LABELS[period]})),source:controlsSource};
snapshot.queries.reporting_days={rows:availableDays(snapshot.queries).map(date=>({date})),source:controlsSource};
snapshot.filters=[{id:'period',field:'period',label:'Reporting period',defaultValue:'last7',queryIds:['reporting_presets']},{id:'customRange',field:'date',label:'Custom reporting dates',mode:'range',defaultValue:'all',queryIds:['reporting_days']}];
snapshot.buildStatus=snapshot.buildStatus==='creating'?'creating':'updating';
await writeFile(path,JSON.stringify(snapshot,null,2)+'\n');
console.log(JSON.stringify({installed:true,protectedRuntimeChanged:false,artifactId:snapshot.id,buildRequired:true}));
